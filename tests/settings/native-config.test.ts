import { expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { NativeConfig, nativeConfigLayout } from "../../src/settings/native-config.ts";

async function temporary(): Promise<string> {
  return mkdtemp(join(tmpdir(), "native-config-"));
}

test("classic Quake reads and writes config.cfg in its game folder with quoted bindings and bare variables", async () => {
  const gamedir = await temporary();
  await writeFile(join(gamedir, "config.cfg"), 'bind "TAB" "+showscores"\r\nsensitivity "3"\r\n');
  const layout = nativeConfigLayout({ family: "q1", edition: "classic", contentDirectory: "q1/id1", looseRoot: gamedir });
  if (layout === null) throw new Error("expected a layout");
  expect(layout.files.map(file => file.path)).toEqual([join(gamedir, "config.cfg")]);
  const native = new NativeConfig(layout);
  expect(await native.readScript()).toBe('bind "TAB" "+showscores"\nsensitivity "3"\n');
  expect(native.filterArchive([{ name: "sensitivity", value: "9" }])).toEqual([]);
  await native.write(
    [
      ["TAB", "+showscores"],
      ["MOUSE1", "+attack"],
    ],
    ['sensitivity "4"'],
  );
  expect(await readFile(join(gamedir, "config.cfg"), "utf8")).toBe('bind "TAB" "+showscores"\nbind "MOUSE1" "+attack"\nsensitivity "4"\n');
});

test("Quake II and Quake III write the id header and unquoted key names", async () => {
  const q2 = await temporary(),
    q3 = await temporary();
  const two = nativeConfigLayout({ family: "q2", edition: "classic", contentDirectory: "q2/baseq2", looseRoot: q2 });
  const three = nativeConfigLayout({ family: "q3", edition: "classic", contentDirectory: "q3a/baseq3", looseRoot: q3 });
  if (two === null || three === null) throw new Error("expected layouts");
  await new NativeConfig(two).write([["TAB", "inven"]], ['set crosshair "1"']);
  await new NativeConfig(three).write([["TAB", "+scores"]], ['seta cg_fov "100"']);
  expect(await readFile(join(q2, "config.cfg"), "utf8")).toBe('// generated by quake, do not modify\nbind TAB "inven"\nset crosshair "1"\n');
  expect(await readFile(join(q3, "q3config.cfg"), "utf8")).toBe('// generated by quake, do not modify\nbind TAB "+scores"\nseta cg_fov "100"\n');
  expect(three.script).toBe("q3config.cfg");
});

test("a native file holding only the id header does not displace the user store", async () => {
  const q3 = await temporary();
  await writeFile(join(q3, "q3config.cfg"), "// generated by quake, do not modify");
  const layout = nativeConfigLayout({ family: "q3", edition: "classic", contentDirectory: "q3a/baseq3", looseRoot: q3 });
  if (layout === null) throw new Error("expected a layout");
  const native = new NativeConfig(layout);
  expect(await native.readScript()).toBeNull();
  const entries = [{ name: "cg_fov", value: "90" }];
  expect(native.filterArchive(entries)).toEqual(entries);
  expect(native.suppressesProfileBindings()).toBe(false);
});

test("a game without a folder to write into keeps the user store", () => {
  expect(nativeConfigLayout({ family: "q1", edition: "classic", contentDirectory: "q1/id1", looseRoot: null })).toBeNull();
});

test("rerelease Quake II places files under Saved Games and merges instead of rewriting them", async () => {
  const home = await temporary();
  const saved = join(home, "Saved Games", "Nightdive Studios", "Quake II");
  await mkdir(join(saved, "baseq2"), { recursive: true });
  await writeFile(join(saved, "system.cfg"), 'set hostname "Mine"\nset fov "90"\n');
  await writeFile(join(saved, "kexengine.cfg"), 'seta snd_volume "0.85"\r\n');
  await writeFile(join(saved, "baseq2", "keybinds.cfg"), 'bind TAB "cmd help"\nbind SPACE "+moveup"\n');
  await writeFile(join(saved, "baseq2", "settings.cfg"), 'set crosshair_0 "3"\n');
  const layout = nativeConfigLayout({ family: "q2", edition: "rerelease", contentDirectory: "q2/rerelease/baseq2", looseRoot: null }, home);
  if (layout === null) throw new Error("expected a layout");
  expect(layout.files.map(file => file.path)).toEqual([
    join(saved, "kexengine.cfg"),
    join(saved, "system.cfg"),
    join(saved, "baseq2", "settings.cfg"),
    join(saved, "baseq2", "keybinds.cfg"),
  ]);
  const native = new NativeConfig(layout);
  expect(await native.readScript()).toContain('bind "TAB" "cmd help"');
  expect(
    native.filterArchive([
      { name: "fov", value: "1" },
      { name: "fresh", value: "2" },
    ]),
  ).toEqual([{ name: "fresh", value: "2" }]);
  await native.write([["TAB", "inven"]], ['set fov "100"', 'seta snd_volume "0.5"', 'set unknown "1"']);
  expect(await readFile(join(saved, "system.cfg"), "utf8")).toBe('set hostname "Mine"\nset fov "100"\n');
  expect(await readFile(join(saved, "kexengine.cfg"), "utf8")).toBe('seta snd_volume "0.5"\r\n');
  expect(await readFile(join(saved, "baseq2", "keybinds.cfg"), "utf8")).toBe('bind TAB "inven"\n');
  expect(await readFile(join(saved, "baseq2", "settings.cfg"), "utf8")).toBe('set crosshair_0 "3"\n');
});

test("rerelease Quake translates its starred actions and keeps the engine's own menu bindings", async () => {
  const home = await temporary();
  const saved = join(home, "Saved Games", "Nightdive Studios", "Quake");
  await mkdir(saved, { recursive: true });
  await writeFile(join(saved, "kexengine.cfg"), 'bind enter "*menu_select"\r\nbind space "*in_jump"\r\nbind mouse_left "*in_attack"\r\nseta volume "0.7"\r\n');
  const layout = nativeConfigLayout({ family: "q1", edition: "rerelease", contentDirectory: "q1/rerelease/id1", looseRoot: null }, home);
  if (layout === null) throw new Error("expected a layout");
  const native = new NativeConfig(layout);
  expect(await native.readScript()).toBe('bind "space" "+jump"\nbind "mouse1" "+attack"\nseta volume "0.7"\n');
  await native.write([["SPACE", "+jump"]], ['seta volume "0.9"']);
  expect(await readFile(join(saved, "kexengine.cfg"), "utf8")).toBe('bind enter "*menu_select"\r\nbind space "*in_jump"\r\nseta volume "0.9"\r\n');
});

